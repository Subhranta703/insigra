create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  company_name text not null check (length(trim(company_name)) > 0)
);
create table if not exists public.campaign_data (
  id bigint generated by default as identity primary key,
  company_name text not null check (length(trim(company_name)) > 0),
  channel text not null,
  leads integer not null check (leads >= 0)
);
alter table public.profiles enable row level security;
alter table public.campaign_data enable row level security;
drop policy if exists "Users can read their own profile" on public.profiles;
create policy "Users can read their own profile" on public.profiles for select to authenticated using (id = auth.uid());
drop policy if exists "Users can read their company campaign data" on public.campaign_data;
create policy "Users can read their company campaign data" on public.campaign_data for select to authenticated using (
  company_name = (select p.company_name from public.profiles p where p.id = auth.uid())
);
create index if not exists campaign_data_company_name_idx on public.campaign_data(company_name);
